def search_local(query, top_k=10, min_quality=None, filename=None, section=None):
    scores = cosine_similarity(vectorizer.transform([query]), tfidf_matrix).flatten()
    result = chunks.copy()
    result["search_score"] = scores

    if min_quality is not None:
        quality = pd.to_numeric(result["quality_score"], errors="coerce").fillna(0)
        result = result[quality >= min_quality]
    if filename:
        result = result[result["filename"].fillna("").str.contains(filename, case=False, regex=False)]
    if section:
        result = result[result["section_title"].fillna("").str.contains(section, case=False, regex=False)]

    result = result.sort_values("search_score", ascending=False).head(top_k)
    return result[[
        "chunk_id", "filename", "section_title", "page_start", "page_end", "page_label_start",
        "quality_score", "search_score", "text"
    ]].reset_index(drop=True)

