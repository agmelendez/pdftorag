def normalize_unicode(text):

    if not text:
        return ""

    text = unicodedata.normalize(
        "NFKC",
        text
    )

    text = text.replace(
        "\u00ad",
        ""
    )

    text = text.replace(
        "\xa0",
        " "
    )

    return text


def normalize_text(text):

    if not text:
        return ""

    text = normalize_unicode(
        text
    )

    text = re.sub(
        r"[ \t]+",
        " ",
        text
    )

    text = re.sub(
        r" *\n *",
        "\n",
        text
    )

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text
    )

    lines = [

        line.strip()

        for line
        in text.splitlines()

        if line.strip()

    ]

    return "\n".join(
        lines
    ).strip()


def single_line(text):

    return re.sub(

        r"\s+",

        " ",

        normalize_unicode(
            text or ""
        )

    ).strip()


def word_count(text):

    return len(

        re.findall(

            r"\b[\wÀ-ÿ]+\b",

            text or "",

            flags=re.UNICODE

        )

    )


def sha256_file(path):

    sha = hashlib.sha256()

    with open(
        path,
        "rb"
    ) as f:

        while True:

            chunk = f.read(
                1024 * 1024
            )

            if not chunk:
                break

            sha.update(
                chunk
            )

    return sha.hexdigest()


def stable_id(
    prefix,
    value
):

    digest = hashlib.sha256(

        value.encode(
            "utf-8",
            errors="ignore"
        )

    ).hexdigest()[:16]

    return (
        f"{prefix}_{digest}"
    )


