class CorpusBuilder:
    def __init__(self):
        self.documents, self.pages, self.sections = [], [], []
        self.chunks, self.tables, self.tables_rejected = [], [], []
        self.errors, self.log = [], []
        self.integrity = {}

    # -------------------------------------------------------- descubrimiento
    def discover(self):
        if not PDF_DIRECTORY.exists():
            raise FileNotFoundError(f"No existe {PDF_DIRECTORY}")
        pdfs = sorted(p for p in PDF_DIRECTORY.rglob("*") if p.is_file() and p.suffix.lower() == ".pdf")
        return pdfs[:MAX_DOCUMENTS] if MAX_DOCUMENTS is not None else pdfs

    # -------------------------------------------------------- proceso
    def process(self):
        pdfs = self.discover()
        print("=" * 90)
        print(f"CIOdD-UCR PDF INTELLIGENCE PIPELINE V{PIPELINE_VERSION}  (Research & RAG Edition)")
        print("=" * 90)
        print(f"\nPDF encontrados: {len(pdfs)}\nEntrada: {PDF_DIRECTORY}\nSalida:  {OUTPUT_DIRECTORY}\n")
        self.inputs = []

        for pdf_path in tqdm(pdfs, desc="Procesando"):
            start = time.time()
            try:
                result = DOCUMENT_EXTRACTOR.extract(str(pdf_path))
                document, pages = result["document"], result["pages"]
                document_id = document["document_id"]
                sections = SECTION_BUILDER.build(document_id, pages)

                tables_by_page = defaultdict(list)
                for t in result["tables"]:
                    tables_by_page[t["page_number"]].append(t["table_id"])
                quality_by_page = {p["page_number"]: float(p.get("overall_quality_score", 0) or 0) for p in pages}
                label_by_page = {p["page_number"]: p.get("page_label", "") for p in pages}
                chunks = CHUNK_BUILDER.build(document_id, document["filename"], sections,
                                             tables_by_page, quality_by_page, label_by_page)

                section_words = sum(word_count(p["text"]) for s in sections for p in s["paragraphs"])
                chunk_unique = sum(c["unique_words"] for c in chunks)
                n_pages = max(1, len(pages))
                ocr_pages = sum(p.get("extraction_source") == "ocr" for p in pages)
                low_text = sum(("low_text" in p.get("page_flags", []) or "empty" in p.get("page_flags", [])) for p in pages)
                document.update({
                    "extracted_pages": len(pages),
                    "total_words": sum(p.get("word_count", 0) for p in pages),
                    "total_tables": len(result["tables"]),
                    "tables_rejected": len(result["tables_rejected"]),
                    "total_sections": len(sections),
                    "sections_with_detected_title": sum(s.get("title_source") == "detected" for s in sections),
                    "total_chunks": len(chunks),
                    "ocr_pages": ocr_pages, "low_text_pages": low_text,
                    "headings_demoted": result["headings_demoted"],
                    "section_words": section_words, "chunk_unique_words": chunk_unique,
                    "chunk_coverage": round(chunk_unique / section_words, 4) if section_words else 1.0,
                    "average_quality": round(float(np.mean([float(p.get("overall_quality_score", 0) or 0) for p in pages])), 4) if pages else 0,
                    "average_extraction_quality": round(float(np.mean([float(p.get("extraction_quality_score", 0) or 0) for p in pages])), 4) if pages else 0,
                    "profile_type_observed": ("scanned" if ocr_pages / n_pages >= 0.8
                                              else "digital" if ocr_pages == 0 and low_text / n_pages < 0.05
                                              else "hybrid"),
                    "repeated_header_footer_patterns": result["repeated_lines"],
                })
                self.documents.append(document); self.pages.extend(pages)
                self.sections.extend(sections); self.chunks.extend(chunks)
                self.tables.extend(result["tables"]); self.tables_rejected.extend(result["tables_rejected"])
                self.errors.extend(result["errors"])
                self.inputs.append({"filename": document["filename"], "sha256": document["sha256"],
                                    "size_bytes": document["file_size_bytes"]})
                self.log.append({"document_id": document_id, "filename": document["filename"], "status": "ok",
                                 "seconds": round(time.time() - start, 3), "pages": len(pages),
                                 "words": document["total_words"], "tables": len(result["tables"]),
                                 "tables_rejected": len(result["tables_rejected"]), "sections": len(sections),
                                 "chunks": len(chunks), "ocr_pages": ocr_pages,
                                 "chunk_coverage": document["chunk_coverage"],
                                 "quality": document["average_quality"]})
            except Exception as e:
                self.errors.append({"filename": pdf_path.name, "stage": "document", "error": str(e), "timestamp": utc_now()})
                self.log.append({"filename": pdf_path.name, "status": "failed", "error": str(e)})

        print("\n💾 Guardando corpus estructurado...")
        self.export_base()
        print("✅ Corpus base guardado.")

        try:
            print("\n🗄️ Construyendo DuckDB..."); self.build_duckdb(); print("✅ DuckDB generado.")
        except Exception as e:
            print(f"⚠️ DuckDB: {e}"); self.errors.append({"stage": "duckdb", "error": str(e), "timestamp": utc_now()})

        if BUILD_TFIDF and self.chunks:
            try:
                print("\n🔎 Construyendo índice TF-IDF..."); self.build_tfidf(); print("✅ TF-IDF generado.")
            except Exception as e:
                print(f"⚠️ TF-IDF: {e}"); self.errors.append({"stage": "tfidf", "error": str(e), "timestamp": utc_now()})

        if GENERATE_EMBEDDINGS and self.chunks:
            try:
                print("\n🧠 Generando embeddings..."); self.build_embeddings(); print("✅ Embeddings y FAISS generados.")
            except Exception as e:
                print("\n⚠️ EMBEDDINGS NO GENERADOS. El corpus principal está completo.\nError:", e)
                self.errors.append({"stage": "embeddings", "error": str(e), "timestamp": utc_now()})

        self.check_integrity()
        write_json(OUTPUT_DIRECTORY / "data_dictionary.json", DATA_DICTIONARY)
        self.write_quality_report()
        self.write_logs()
        self.write_manifest()
        self.summary()

    # -------------------------------------------------------- exportación
    def export_dataset(self, name, rows, parquet=True):
        write_jsonl(OUTPUT_DIRECTORY / f"{name}.jsonl", rows)
        if rows and parquet:
            pd.DataFrame([flatten_row(r) for r in rows]).to_parquet(OUTPUT_DIRECTORY / f"{name}.parquet", index=False)

    def export_base(self):
        for name, rows in [("documents", self.documents), ("pages", self.pages), ("sections", self.sections),
                           ("chunks", self.chunks), ("tables", self.tables)]:
            self.export_dataset(name, rows)
        self.export_dataset("tables_rejected", self.tables_rejected, parquet=False)
        self.write_logs()

    def write_logs(self):
        write_jsonl(OUTPUT_DIRECTORY / "processing_log.jsonl", self.log)
        write_jsonl(OUTPUT_DIRECTORY / "errors.jsonl", self.errors)

    # -------------------------------------------------------- DuckDB
    def build_duckdb(self):
        path = OUTPUT_DIRECTORY / "corpus.duckdb"
        if path.exists():
            path.unlink()
        con = duckdb.connect(str(path))
        try:
            for name in ["documents", "pages", "sections", "chunks", "tables"]:
                parquet = OUTPUT_DIRECTORY / f"{name}.parquet"
                if parquet.exists():
                    safe = str(parquet).replace("'", "''")
                    con.execute(f"CREATE TABLE {name} AS SELECT * FROM read_parquet('{safe}')")
            for stmt in ["CREATE INDEX idx_chunks_document ON chunks(document_id)",
                         "CREATE INDEX idx_pages_document ON pages(document_id, page_number)"]:
                try:
                    con.execute(stmt)
                except Exception:
                    pass
        finally:
            con.close()

    # -------------------------------------------------------- índices
    @staticmethod
    def retrieval_text(chunk):
        """Texto para indexar: el título solo se antepone si proviene de un encabezado fiable."""
        title = chunk.get("section_title", "") if chunk.get("section_title_reliable") else ""
        return (title + "\n" + chunk.get("text", "")).strip()

    def build_tfidf(self):
        import joblib
        from sklearn.feature_extraction.text import TfidfVectorizer
        texts = [self.retrieval_text(c) for c in self.chunks]
        vectorizer = TfidfVectorizer(lowercase=True, strip_accents="unicode", ngram_range=(1, 2),
                                     max_df=0.95, min_df=1, max_features=100_000, sublinear_tf=True, norm="l2")
        matrix = vectorizer.fit_transform(texts)
        joblib.dump(vectorizer, OUTPUT_DIRECTORY / "tfidf_vectorizer.joblib")
        joblib.dump(matrix, OUTPUT_DIRECTORY / "tfidf_matrix.joblib")

    def build_embeddings(self):
        from sentence_transformers import SentenceTransformer
        import faiss
        model = SentenceTransformer(EMBEDDING_MODEL)
        texts = [self.retrieval_text(c) for c in self.chunks]
        embeddings = np.asarray(model.encode(texts, batch_size=EMBEDDING_BATCH_SIZE,
                                             show_progress_bar=True, normalize_embeddings=True), dtype="float32")
        np.save(OUTPUT_DIRECTORY / "embeddings.npy", embeddings)
        index = faiss.IndexFlatIP(embeddings.shape[1])
        index.add(embeddings)
        faiss.write_index(index, str(OUTPUT_DIRECTORY / "faiss.index"))
        write_jsonl(OUTPUT_DIRECTORY / "faiss_mapping.jsonl", [
            {"faiss_row": i, "chunk_id": c["chunk_id"], "document_id": c["document_id"], "filename": c["filename"],
             "section_title": c["section_title"], "page_start": c["page_start"], "page_end": c["page_end"]}
            for i, c in enumerate(self.chunks)])

    # -------------------------------------------------------- integridad (auditoría incorporada)
    def check_integrity(self):
        checks, warnings = [], []

        def add(name, ok, detail="", severity="FAIL"):
            checks.append({"check": name, "status": "PASS" if ok else severity, "detail": detail})

        def unique(rows, key):
            vals = [r.get(key) for r in rows]
            return len(vals) == len(set(vals))

        add("ids únicos (documents/pages/sections/chunks/tables)",
            all([unique(self.documents, "document_id"), unique(self.pages, "page_id"),
                 unique(self.sections, "section_id"), unique(self.chunks, "chunk_id"),
                 unique(self.tables, "table_id")]))
        docs = {d["document_id"]: d for d in self.documents}
        add("páginas extraídas == page_count del PDF",
            all(d["extracted_pages"] == d["page_count"] for d in self.documents),
            str([d["filename"] for d in self.documents if d["extracted_pages"] != d["page_count"]]))
        bad_rng = [c["chunk_id"] for c in self.chunks
                   if not (1 <= c["page_start"] <= c["page_end"] <= docs[c["document_id"]]["page_count"])]
        add("rango de páginas de chunks válido", not bad_rng, str(bad_rng[:5]))
        sec_ids = {s["section_id"] for s in self.sections}
        add("chunks apuntan a secciones existentes", all(c["section_id"] in sec_ids for c in self.chunks))
        add("todo documento tiene chunks", all(d["total_chunks"] > 0 for d in self.documents),
            str([d["filename"] for d in self.documents if d["total_chunks"] == 0]))
        low_cov = [(d["filename"], d["chunk_coverage"]) for d in self.documents if d["chunk_coverage"] < CHUNK_COVERAGE_MIN]
        add(f"cobertura de texto en chunks >= {CHUNK_COVERAGE_MIN}", not low_cov, str(low_cov))

        covered = defaultdict(set)
        for c in self.chunks:
            for p in range(c["page_start"], c["page_end"] + 1):
                covered[c["document_id"]].add(p)
        uncovered = [(p["filename"], p["page_number"], p["word_count"]) for p in self.pages
                     if p.get("word_count", 0) >= 20 and p["page_number"] not in covered[p["document_id"]]]
        add("páginas con texto sin ningún chunk", not uncovered, str(uncovered[:10]), "WARNING")

        groups = defaultdict(set)
        for c in self.chunks:
            groups[c["text_sha256"]].add(c["document_id"])
        dup = sum(len(v) > 1 for v in groups.values())
        add("chunks idénticos entre documentos distintos", dup == 0, f"{dup} grupos", "WARNING")

        flagged = [(p["filename"], p["page_number"], p["page_flags"]) for p in self.pages
                   if {"empty", "low_text", "ocr_low_confidence", "page_error"} & set(p.get("page_flags", []))]
        add("páginas con texto escaso/OCR dudoso (revisar visualmente antes de citar)", not flagged,
            f"{len(flagged)} páginas; ver quality_report.review_pages", "WARNING")

        status = "FAIL" if any(c["status"] == "FAIL" for c in checks) else \
                 "PASS_WITH_WARNINGS" if any(c["status"] == "WARNING" for c in checks) else "PASS"
        self.integrity = {"generated_at": utc_now(), "status": status, "checks": checks,
                          "review_pages": [{"filename": f, "page_number": n, "flags": fl} for f, n, fl in flagged]}
        write_json(OUTPUT_DIRECTORY / "integrity_report.json", self.integrity)

