class PDFProfiler:
    """Perfil técnico del PDF. Los metadatos internos NO prueban autoría ni fecha."""

    @staticmethod
    def classify(document):
        n_pages = len(document)
        if n_pages == 0:
            return "empty"
        sample = sorted({int(round(i * (n_pages - 1) / 6)) for i in range(7)}) if n_pages > 7 else list(range(n_pages))
        with_text = 0
        for idx in sample:
            text = normalize_text(document[idx].get_text("text", sort=True))
            if word_count(text) >= 20:
                with_text += 1
        if with_text == len(sample):
            return "digital"
        if with_text == 0:
            return "scanned"
        return "hybrid"

    def profile(self, pdf_path):
        result = {
            "filename": Path(pdf_path).name,
            "file_size_bytes": os.path.getsize(pdf_path),
            "sha256": sha256_file(pdf_path),
            "title": "", "author": "", "subject": "", "creator": "", "producer": "",
            "pdf_creation_date": "",
            "page_count": 0, "encrypted": False, "profile_type": "unknown",
        }
        try:
            reader = pypdf.PdfReader(pdf_path)
            result["page_count"] = len(reader.pages)
            result["encrypted"] = bool(reader.is_encrypted)
            metadata = reader.metadata or {}
            for target, source in {"title": "/Title", "author": "/Author", "subject": "/Subject",
                                   "creator": "/Creator", "producer": "/Producer",
                                   "pdf_creation_date": "/CreationDate"}.items():
                result[target] = str(metadata.get(source, "") or "")
        except Exception as e:
            result["metadata_error"] = str(e)
        try:
            document = pymupdf.open(pdf_path)
            result["profile_type"] = self.classify(document)
            document.close()
        except Exception as e:
            result["profile_error"] = str(e)
        return result

