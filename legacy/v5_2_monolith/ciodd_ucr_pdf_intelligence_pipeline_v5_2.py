def infer_repeated_lines(pages):
    """Patrones (números -> '#') de las líneas de borde que se repiten en muchas páginas.
    Detecta '28 Título del informe' / 'Título del informe 29' / 'EN 12 EN' / números de página."""
    if len(pages) < 3:
        return set()
    counter = Counter()
    k = HEADER_FOOTER_EDGE_LINES
    for page in pages:
        lines = [single_line(x) for x in (page.get("native_text", "") or "").splitlines() if single_line(x)]
        edge = lines[:k] + lines[-k:]
        for pattern in {normalize_pattern(x) for x in edge if 1 <= len(x) <= 140}:
            counter[pattern] += 1
    minimum = max(3, math.ceil(len(pages) * HEADER_FOOTER_THRESHOLD))
    return {p for p, c in counter.items() if c >= minimum and p.strip()}


def is_repeated_line(line, patterns):
    """Coincide con un patrón de cabecera/pie, ya sea como línea completa o porque
    todos sus tokens lo son (p. ej. el bloque 'EN 15 EN' frente a las líneas 'EN', '15', 'EN')."""
    norm = normalize_pattern(line)
    if norm in patterns:
        return True
    tokens = single_line(line).split()
    return bool(tokens) and all(normalize_pattern(t) in patterns for t in tokens)


def remove_repeated_lines(text, patterns):
    """Quita SOLO líneas de borde (primeras/últimas k) que coinciden con un patrón.
    Devuelve (texto_limpio, líneas_removidas) para conservar la trazabilidad."""
    if not patterns or not text:
        return normalize_text(text), []
    lines = text.splitlines()
    k = HEADER_FOOTER_EDGE_LINES
    keep, removed = [], []
    last = len(lines) - 1
    for i, line in enumerate(lines):
        at_edge = i < k or i > last - k
        if at_edge and single_line(line) and is_repeated_line(line, patterns):
            removed.append(single_line(line))
        else:
            keep.append(line)
    return normalize_text("\n".join(keep)), removed


def clean_blocks(blocks, patterns, page_height):
    """Elimina del layout las líneas de cabecera/pie (por patrón Y por posición en la página)."""
    if not patterns:
        return blocks
    cleaned = []
    for block in blocks:
        bbox = block.get("bbox") or []
        in_edge = bool(page_height and len(bbox) == 4 and (bbox[3] < 0.12 * page_height or bbox[1] > 0.88 * page_height))
        if in_edge and is_repeated_line(" ".join(block.get("text", "").split()), patterns):
            continue        # el bloque completo es cabecera/pie ('EN\n16\nEN' == 'EN 16 EN')
        if in_edge:
            kept = [ln for ln in block.get("text", "").splitlines() if not is_repeated_line(ln, patterns)]
            if not kept:
                continue
            block = dict(block)
            block["text"] = "\n".join(kept)
        cleaned.append(block)
    return cleaned

