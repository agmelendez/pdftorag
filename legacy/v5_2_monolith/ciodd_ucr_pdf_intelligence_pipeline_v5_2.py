def extraction_quality(text_metrics, source, ocr_confidence):
    """Calidad TÉCNICA del texto de la página (legibilidad, codificación, estructura de tokens).
    A diferencia de `overall_quality_score` no premia que la página tenga tablas o
    encabezados, ni castiga páginas cortas legítimas (portadas, últimas páginas)."""
    base = (0.30 * text_metrics["encoding_score"] + 0.40 * text_metrics["legibility_score"]
            + 0.30 * text_metrics["token_structure_score"])
    if source == "ocr":
        base *= max(0.0, min(1.0, float(ocr_confidence or 0)))
    return round(base, 4)


_GENERIC_TITLE = re.compile(r"^(summary|executive summary|contents|table of contents|about this report|foreword|preface|acknowledg\w+|abstract|resumen|[ií]ndice|disclaimer|copyright)\b", re.I)
_BAD_TITLE = re.compile(r"(^untitled$|^microsoft word|\.(pdf|docx?|indd|pptx?)$|^slide \d|^document\d*$)", re.I)


def infer_document_metadata(profile, pages):
    """Título, año candidato e idioma INFERIDOS. Son pistas para el catálogo,
    no prueba de autoría ni de fecha: verificar contra la portada."""
    meta = {}
    title = single_line(profile.get("title", ""))
    if len(title) >= 8 and not _BAD_TITLE.search(title):
        meta["inferred_title"], meta["title_source"] = title, "pdf_metadata"
    else:
        # Se busca primero en la portada (pág. 1) y solo después en las páginas 2-3.
        for scope, label in ((pages[:1], "largest_font_cover"), (pages[1:3], "largest_font_pages_2_3")):
            cands = []
            for p in scope:
                for b in p.get("blocks", []):
                    spans = b.get("spans") or []
                    t = single_line(b.get("text", ""))
                    if (spans and 2 <= len(t.split()) <= 25 and not re.fullmatch(r"[\W\d_]+", t)
                            and not _GENERIC_TITLE.search(t) and not re.search(r"\.{4,}|…{2,}", t)):
                        cands.append((max(s["font_size"] for s in spans), p["page_number"],
                                      (b.get("bbox") or [0, 0, 0, 0])[1], t))
            if cands:
                top = max(c[0] for c in cands)
                best = sorted([c for c in cands if c[0] >= top - 0.5 and c[1] == min(
                    x[1] for x in cands if x[0] >= top - 0.5)], key=lambda c: c[2])
                meta["inferred_title"] = " ".join(c[3] for c in best)[:300]
                meta["title_source"] = label
                break
        else:
            meta["inferred_title"] = Path(profile.get("filename", "")).stem
            meta["title_source"] = "filename"

    years = Counter()
    for p in pages[:2]:
        years.update(re.findall(r"\b(19[89]\d|20[0-3]\d)\b", p.get("clean_text", "") or ""))
    meta["year_candidates"] = [y for y, _ in years.most_common(3)]    # candidatos, NO fecha de publicación
    langs = Counter(p.get("language") for p in pages if p.get("language") not in (None, "unknown"))
    meta["document_language"] = langs.most_common(1)[0][0] if langs else "unknown"
    meta["metadata_note"] = ("Título, año e idioma son inferencias automáticas; verificar contra la portada. "
                             "Los metadatos internos del PDF no prueban autoría ni fecha.")
    return meta


class DocumentExtractor:
    def __init__(self):
        self.profiler = PDFProfiler()

    def extract(self, pdf_path):
        profile = self.profiler.profile(pdf_path)
        document_id = stable_id("doc", profile["sha256"])
        document = {"document_id": document_id, **profile, "processed_at": utc_now()}
        pages, tables, rejected, errors = [], [], [], []

        pdf = pymupdf.open(pdf_path)
        plumber_pdf = None
        try:
            try:
                plumber_pdf = pdfplumber.open(pdf_path)
            except Exception as e:
                errors.append({"document_id": document_id, "stage": "pdfplumber_open", "error": str(e)})

            for page_index in range(len(pdf)):
                page_number = page_index + 1
                page = pdf[page_index]
                try:
                    native_text = normalize_text(page.get_text("text", sort=True))
                    native_metrics = QUALITY.text_quality(native_text)

                    layout = LAYOUT.extract(page)
                    blocks, median_font = layout["blocks"], layout["median_font_size"]
                    heading_count = 0
                    for block in blocks:
                        info = HEADING.detect(block, median_font, float(page.rect.width),
                                              float(page.rect.height), page_number)
                        block.update(info)
                        heading_count += int(info["is_heading"])

                    final_text, extraction_source = native_text, "native"
                    ocr_applied, ocr_text, ocr_confidence = False, "", None
                    if OCR_ENABLED and OCR.needs_ocr(native_text, native_metrics["text_quality_score"]):
                        ocr_result = OCR.extract(page)
                        ocr_applied = True
                        ocr_text, ocr_confidence = ocr_result["text"], ocr_result["confidence"]
                        if (word_count(ocr_text) > max(1, word_count(native_text)) * 1.20
                                or word_count(native_text) < OCR_MIN_WORDS):
                            final_text, extraction_source = ocr_text, "ocr"

                    page_tables = []
                    if plumber_pdf is not None:
                        try:
                            found = TABLE_EXTRACTOR.extract(plumber_pdf.pages[page_index], document_id, page_number)
                            page_tables = found["accepted"]
                            rejected.extend(found["rejected"])
                        except Exception as e:
                            errors.append({"document_id": document_id, "page_number": page_number,
                                           "stage": "tables", "error": str(e)})
                    tables.extend(page_tables)

                    final_metrics = QUALITY.text_quality(final_text)
                    page_quality = QUALITY.page_quality(final_metrics, extraction_source, ocr_confidence,
                                                        len(blocks), len(page_tables), heading_count)
                    words = word_count(final_text)
                    flags = []
                    if extraction_source == "ocr":
                        flags.append("ocr")
                        if (ocr_confidence or 0) < 0.60:
                            flags.append("ocr_low_confidence")
                    if words == 0:
                        flags.append("empty")
                    elif words < 20:
                        flags.append("low_text")
                    if not blocks:
                        flags.append("no_layout_blocks")
                    if layout["images"] and words < 30:
                        flags.append("image_page")
                    try:
                        label = page.get_label() or ""
                    except Exception:
                        label = ""

                    pages.append({
                        "page_id": f"{document_id}_P{page_number:05d}",
                        "document_id": document_id, "filename": profile["filename"],
                        "page_number": page_number,          # índice 1-based del PDF
                        "page_label": label,                 # etiqueta impresa si el PDF la define
                        "width": float(page.rect.width), "height": float(page.rect.height),
                        "native_text": native_text, "ocr_text": ocr_text,
                        "clean_text": normalize_text(final_text),
                        "extraction_source": extraction_source, "ocr_applied": ocr_applied,
                        "ocr_confidence": ocr_confidence,
                        "word_count": words, "language": detect_language(final_text),
                        "block_count": len(blocks), "heading_count": heading_count,
                        "image_count": len(layout["images"]), "table_count": len(page_tables),
                        "page_flags": flags,
                        "extraction_quality_score": extraction_quality(final_metrics, extraction_source, ocr_confidence),
                        "blocks": blocks, "images_metadata": layout["images"],
                        **final_metrics, **page_quality,
                    })
                except Exception as e:
                    errors.append({"document_id": document_id, "page_number": page_number,
                                   "stage": "page", "error": str(e)})
                    pages.append({"page_id": f"{document_id}_P{page_number:05d}",
                                  "document_id": document_id, "filename": profile["filename"],
                                  "page_number": page_number, "page_label": "", "clean_text": "",
                                  "word_count": 0, "overall_quality_score": 0,
                                  "extraction_quality_score": 0, "blocks": [],
                                  "page_flags": ["page_error"], "error": str(e)})
        finally:
            pdf.close()
            if plumber_pdf:
                plumber_pdf.close()

        # ---- cabeceras/pies corridos (solo en bordes; se registran las líneas removidas) ----
        repeated = infer_repeated_lines(pages)
        for page in pages:
            height = page.get("height")
            page["clean_text"], removed = remove_repeated_lines(page.get("clean_text", ""), repeated)
            page["removed_edge_lines"] = sorted(set(removed))
            page["word_count"] = word_count(page["clean_text"])
            page["blocks"] = clean_blocks(page.get("blocks", []), repeated, height)

        demoted = demote_repeated_headings(pages)
        document.update(infer_document_metadata(profile, pages))
        return {"document": document, "pages": pages, "tables": tables, "tables_rejected": rejected,
                "errors": errors, "repeated_lines": sorted(repeated), "headings_demoted": demoted}


