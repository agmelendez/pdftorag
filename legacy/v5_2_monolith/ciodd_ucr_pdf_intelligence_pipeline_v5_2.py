class AdaptiveTableExtractor:
    """Extrae tablas con pdfplumber y las CLASIFICA.

    V5.1 guardaba como tabla casi cualquier rejilla de la estrategia 'text'
    (868 "tablas" en 863 páginas, la mayoría prosa fragmentada en celdas
    como 'ap | plies to person | s concerned'). V5.2 conserva en `tables` solo
    las que pasan los criterios y envía el resto a `tables_rejected` con el
    motivo, de modo que nada se pierde en silencio.
    """

    strategies = [
        ("lines", {"vertical_strategy": "lines", "horizontal_strategy": "lines",
                   "snap_tolerance": 3, "join_tolerance": 3, "intersection_tolerance": 3}),
        ("text", {"vertical_strategy": "text", "horizontal_strategy": "text",
                  "min_words_vertical": 3, "min_words_horizontal": 1,
                  "text_x_tolerance": 3, "text_y_tolerance": 3}),
    ]
    caption_re = re.compile(r"^(table|tabla|cuadro|figure|figura|chart|gr[aá]fico|annex|anexo)\s*[\dA-Z]", re.I)

    @staticmethod
    def clean_matrix(table):
        out = []
        for row in (table or []):
            clean = [single_line("" if c is None else str(c)) for c in row]
            if any(clean):
                out.append(clean)
        return out

    @staticmethod
    def features(matrix, bbox, page_area):
        cells = [c for r in matrix for c in r]
        filled = [c for c in cells if c.strip()]
        nf = max(1, len(filled))
        area = 0.0
        if bbox and len(bbox) == 4 and page_area:
            area = max(0.0, (bbox[2] - bbox[0])) * max(0.0, (bbox[3] - bbox[1])) / page_area
        return {
            "filled_ratio": round(len(filled) / max(1, len(cells)), 3),
            "fragment_ratio": round(sum(len(c.strip()) <= 2 for c in filled) / nf, 3),
            "lower_start_ratio": round(sum(c.strip()[:1].islower() for c in filled) / nf, 3),
            "avg_words_per_cell": round(sum(len(c.split()) for c in filled) / nf, 2),
            "page_area_share": round(area, 3),
        }

    def judge(self, strategy, matrix, feats):
        rows, cols = len(matrix), max(len(r) for r in matrix)
        if rows < 2 or cols < 2:
            return False, "menos de 2 filas o 2 columnas"
        if strategy == "lines":
            if feats["filled_ratio"] < TABLE_LINES_MIN_FILLED:
                return False, "celdas mayormente vacías"
            if feats["fragment_ratio"] >= TABLE_LINES_MAX_FRAGMENT:
                return False, "celdas fragmentadas (<=2 caracteres)"
            if feats["lower_start_ratio"] >= 0.5:
                return False, "celdas inician en minúscula (fragmento de texto, no tabla)"
            return True, "ok"
        if rows > TABLE_TEXT_MAX_ROWS or cols > TABLE_TEXT_MAX_COLS:
            return False, "rejilla de texto demasiado grande (prosa en columnas)"
        if feats["lower_start_ratio"] >= TABLE_TEXT_MAX_LOWER_START:
            return False, "celdas inician en minúscula (prosa fragmentada)"
        if feats["fragment_ratio"] >= TABLE_TEXT_MAX_FRAGMENT:
            return False, "celdas fragmentadas (<=2 caracteres)"
        if feats["filled_ratio"] < TABLE_TEXT_MIN_FILLED:
            return False, "celdas mayormente vacías"
        if feats["page_area_share"] >= TABLE_TEXT_MAX_AREA:
            return False, "ocupa casi toda la página (prosa)"
        return True, "ok"

    @staticmethod
    def to_markdown(matrix, max_rows=40):
        def esc(c):
            return (c or "").replace("|", "\\|").replace("\n", " ")
        width = max(len(r) for r in matrix)
        rows = [r + [""] * (width - len(r)) for r in matrix[:max_rows]]
        lines = ["| " + " | ".join(esc(c) for c in rows[0]) + " |",
                 "|" + "|".join(["---"] * width) + "|"]
        lines += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows[1:]]
        if len(matrix) > max_rows:
            lines.append(f"| … ({len(matrix) - max_rows} filas más) |" + " |" * (width - 1))
        return "\n".join(lines)

    def find_caption(self, page, bbox):
        try:
            y0 = max(0.0, bbox[1] - 45.0)
            if bbox[1] - y0 < 8:
                return ""
            text = page.crop((0, y0, page.width, bbox[1])).extract_text() or ""
            for line in reversed([single_line(x) for x in text.splitlines() if single_line(x)]):
                if self.caption_re.match(line):
                    return line[:300]
        except Exception:
            pass
        return ""

    def extract(self, page, document_id, page_number):
        accepted, rejected, seen = [], [], set()
        try:
            page_area = float(page.width) * float(page.height)
        except Exception:
            page_area = 0.0

        for strategy_name, settings in self.strategies:
            try:
                found = page.find_tables(table_settings=settings)
            except Exception:
                found = []
            accepted_here = 0
            for table_object in found:
                try:
                    matrix = self.clean_matrix(table_object.extract())
                except Exception:
                    continue
                if not matrix:
                    continue
                n_cols = max(len(r) for r in matrix)
                matrix = [r + [""] * (n_cols - len(r)) for r in matrix]
                try:
                    bbox = [round(float(v), 2) for v in table_object.bbox]
                except Exception:
                    bbox = []
                fingerprint = hashlib.sha256(json.dumps(matrix, ensure_ascii=False).encode("utf-8")).hexdigest()
                if fingerprint in seen:
                    continue
                seen.add(fingerprint)

                feats = self.features(matrix, bbox, page_area)
                ok, reason = self.judge(strategy_name, matrix, feats)
                headers_raw = matrix[0]
                counter, headers = {}, []
                for i, h in enumerate(headers_raw):
                    base = h if h else f"column_{i + 1}"
                    counter[base] = counter.get(base, 0) + 1
                    headers.append(base if counter[base] == 1 else f"{base}_{counter[base]}")
                record = {
                    "table_id": stable_id("tbl", f"{document_id}|{page_number}|{strategy_name}|{bbox}|{matrix[:3]}"),
                    "document_id": document_id,
                    "page_number": page_number,
                    "strategy": strategy_name,
                    "bbox": bbox,
                    "rows": len(matrix) - 1,
                    "columns": n_cols,
                    "table_confidence": ("high" if strategy_name == "lines" and feats["filled_ratio"] >= 0.5
                                         else "medium" if ok else "low"),
                    "quality_features": feats,
                    "caption": self.find_caption(page, bbox) if bbox else "",
                    "headers": headers,
                    "records": [dict(zip(headers, r)) for r in matrix[1:]],
                    "matrix": matrix,
                }
                if ok:
                    record["markdown"] = self.to_markdown(matrix)
                    accepted.append(record)
                    accepted_here += 1
                else:
                    record["reject_reason"] = reason
                    record.pop("records", None)
                    rejected.append(record)
            if strategy_name == "lines" and accepted_here:
                break           # si 'lines' halló tablas válidas no se prueba 'text'
        return {"accepted": accepted, "rejected": rejected}


