class SectionBuilder:
    """Construye secciones respetando el orden de lectura y sin perder texto.

    Cambios V5.2 respecto a V5.1:
      * encabezados consecutivos se combinan (título multilínea o jerarquía
        'Capítulo › Sección') en vez de que el último borre al anterior;
      * las páginas leídas por OCR usan el texto OCR (V5.1 usaba bloques nativos
        aunque el OCR hubiera ganado);
      * cada sección registra cómo se obtuvo su título (`title_source`) y su
        confianza; `section_title` es alias de `title` (compatibilidad con chunks
        y con el auditor).
    """

    def build(self, document_id, pages):
        sections, state = [], {"current": None, "counter": 0, "last_bottom": None, "last_page": None}

        def start(title, page_number, source, conf=0.0, level=None):
            state["counter"] += 1
            return {"section_id": f"{document_id}_S{state['counter']:04d}",
                    "document_id": document_id, "title": title, "title_source": source,
                    "heading_confidence": conf, "heading_level": level,
                    "page_start": page_number, "page_end": page_number, "paragraphs": []}

        def close():
            cur = state["current"]
            if cur and cur["paragraphs"]:
                sections.append(cur)
            state["current"] = None

        for page in pages:
            pn = page["page_number"]
            blocks = page.get("blocks", []) or []
            if not blocks or page.get("extraction_source") == "ocr":
                text = page.get("clean_text", "")
                if not text:
                    continue
                if state["current"] is None:
                    state["current"] = start("Contenido inicial", pn, "none")
                state["current"]["paragraphs"].append({"page_number": pn, "text": text, "block_id": None})
                state["current"]["page_end"] = pn
                state["last_bottom"] = None
                continue

            for block in blocks:
                text = normalize_text(block.get("text", ""))
                if not text:
                    continue
                bbox = block.get("bbox") or [0, 0, 0, 0]
                if block.get("is_heading"):
                    title = single_line(text)
                    conf = float(block.get("heading_confidence", 0) or 0)
                    level = block.get("heading_level")
                    cur = state["current"]
                    if cur is not None and not cur["paragraphs"]:
                        # encabezado seguido de otro encabezado, sin texto entre ambos
                        adjacent = (state["last_page"] == pn and state["last_bottom"] is not None
                                    and (bbox[1] - state["last_bottom"]) < 24)
                        cur["title"] = (cur["title"] + (" " if adjacent else " › ") + title)[:300]
                        cur["heading_confidence"] = max(cur["heading_confidence"], conf)
                    else:
                        close()
                        state["current"] = start(title[:300], pn, "detected", conf, level)
                    state["last_bottom"], state["last_page"] = bbox[3], pn
                else:
                    if state["current"] is None:
                        state["current"] = start("Contenido inicial", pn, "none")
                    state["current"]["paragraphs"].append(
                        {"page_number": pn, "text": text, "block_id": block.get("block_id")})
                    state["current"]["page_end"] = pn
                    state["last_bottom"] = None

        close()
        for section in sections:
            section["section_title"] = section["title"]
            section["text"] = normalize_text("\n\n".join(p["text"] for p in section["paragraphs"]))
            section["word_count"] = word_count(section["text"])
            section["paragraph_count"] = len(section["paragraphs"])
            section["language"] = detect_language(section["text"])
        return sections


