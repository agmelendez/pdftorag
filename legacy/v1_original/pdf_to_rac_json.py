class CorpusBuilder:
    """Construye corpus final con índices."""

    def __init__(self):
        self.extractor = FastPDFExtractor()
        self.documents = []
        self.metrics = []
        self.indices = {
            'table_of_contents': [],
            'tables_index': [],
            'all_tables_list': []
        }

    def process_pdfs(self, directory: str) -> None:
        """Procesa todos los PDFs."""
        pdf_files = sorted([f for f in os.listdir(directory)
                           if f.lower().endswith('.pdf')])
        pdf_paths = [os.path.join(directory, f) for f in pdf_files]

        print("=" * 80)
        print("PROCESAMIENTO DE PDFs")
        print("=" * 80)
        print(f"\n📁 Directorio: {directory}")
        print(f"📊 PDFs encontrados: {len(pdf_paths)}\n")

        start_time = time.time()

        for idx, pdf_path in enumerate(pdf_paths, 1):
            doc_name = Path(pdf_path).stem[:35]
            print(f"[{idx:2d}/{len(pdf_paths)}] {doc_name:<35}", end=' ', flush=True)

            doc = self.extractor.extract_pdf(pdf_path)
            self.documents.append(doc)

            # Calcular métricas
            total_words = sum(p['text']['word_count'] for p in doc['pages'])
            total_tables = sum(len(p['tables']) for p in doc['pages'])
            avg_quality = sum(p['text']['quality_score'] for p in doc['pages']) / len(doc['pages']) if doc['pages'] else 0

            self.metrics.append({
                'document_id': doc['document_id'],
                'pages': len(doc['pages']),
                'words': total_words,
                'tables': total_tables,
                'quality': round(avg_quality, 3)
            })

            # Mostrar resultado
            emoji = "✓" if avg_quality > 0.5 else "⚠"
            print(f"{emoji} {total_words:>6} w, {total_tables:>3} t, Q={avg_quality:.2f}")

        elapsed = time.time() - start_time
        print("\n" + "=" * 80)
        print(f"✓ {len(self.documents)} documentos procesados en {elapsed:.1f}s\n")

    def build_indices(self) -> None:
        """Genera índices navegables."""
        print("🗂️  GENERACIÓN DE ÍNDICES")
        print("─" * 80)

        # Tabla de contenidos
        for doc in self.documents:
            doc_id = doc['document_id']
            sections = []

            for page in doc['pages']:
                text = page['text']['content']
                lines = text.split('\n')[:5]

                for line in lines:
                    if 20 < len(line) < 150:
                        sections.append({
                            'title': line[:100],
                            'page': page['page_number']
                        })

            if sections:
                self.indices['table_of_contents'].append({
                    'document_id': doc_id,
                    'section_count': len(sections),
                    'sections': sections[:10]
                })

        print(f"✓ Tabla de contenidos: {len(self.indices['table_of_contents'])} documentos")

        # Índice de tablas
        table_counter = 0
        for doc in self.documents:
            doc_id = doc['document_id']

            for page in doc['pages']:
                for table in page['tables']:
                    table_counter += 1
                    self.indices['tables_index'].append({
                        'table_id': f'tbl_{table_counter:04d}',
                        'document_id': doc_id,
                        'page': page['page_number'],
                        'rows': table['rows'],
                        'columns': table['columns']
                    })

                    self.indices['all_tables_list'].append({
                        'table_counter': table_counter,
                        'document': doc_id,
                        'headers': table['headers'][:5],  # Primeros 5 headers
                        'row_count': len(table['data'])
                    })

        print(f"✓ Índice de tablas: {table_counter} tablas")

    def generate_quality_report(self) -> Dict[str, Any]:
        """Genera reporte de calidad."""
        print("\n📊 ANÁLISIS DE CALIDAD")
        print("─" * 80)

        total_words = sum(m['words'] for m in self.metrics)
        total_pages = sum(m['pages'] for m in self.metrics)
        total_tables = sum(m['tables'] for m in self.metrics)

        qualities = [m['quality'] for m in self.metrics]
        avg_quality = sum(qualities) / len(qualities) if qualities else 0

        # Categorizar
        excellent = len([q for q in qualities if q >= 0.8])
        good = len([q for q in qualities if 0.6 <= q < 0.8])
        fair = len([q for q in qualities if 0.4 <= q < 0.6])
        poor = len([q for q in qualities if q < 0.4])

        report = {
            'timestamp': datetime.now().isoformat(),
            'summary': {
                'total_documents': len(self.documents),
                'total_pages': total_pages,
                'total_words': total_words,
                'total_tables': total_tables,
                'avg_quality': round(avg_quality, 3),
                'avg_words_per_doc': round(total_words / len(self.documents), 0) if self.documents else 0,
                'avg_words_per_page': round(total_words / total_pages, 1) if total_pages else 0
            },
            'quality_distribution': {
                'excellent_0.8+': excellent,
                'good_0.6_0.8': good,
                'fair_0.4_0.6': fair,
                'poor_<0.4': poor
            },
            'documents': self.metrics
        }

        # Mostrar
        print(f"Total documentos: {report['summary']['total_documents']}")
        print(f"Total páginas: {report['summary']['total_pages']}")
        print(f"Total palabras: {report['summary']['total_words']:,}")
        print(f"Total tablas: {report['summary']['total_tables']}")
        print(f"Calidad promedio: {report['summary']['avg_quality']:.1%}")
        print(f"\nDistribución:")
        print(f"  Excelente (0.8+):   {excellent:2d} ({excellent/len(self.documents)*100:5.1f}%)")
        print(f"  Buena (0.6-0.8):    {good:2d} ({good/len(self.documents)*100:5.1f}%)")
        print(f"  Regular (0.4-0.6):  {fair:2d} ({fair/len(self.documents)*100:5.1f}%)")
        print(f"  Pobre (<0.4):       {poor:2d} ({poor/len(self.documents)*100:5.1f}%)")

        return report

    def export_results(self, base_name: str = 'corpus') -> None:
        """Exporta todos los resultados."""
        print("\n💾 EXPORTACIÓN DE RESULTADOS")
        print("─" * 80)

        # 1. Corpus limpio
        corpus_data = {
            'corpus_metadata': {
                'creation_date': datetime.now().isoformat(),
                'document_count': len(self.documents),
                'format_version': '4.0_final',
                'processing_status': 'complete_and_validated'
            },
            'documents': self.documents
        }

        corpus_file = f'{base_name}_final.json'
        with open(corpus_file, 'w', encoding='utf-8') as f:
            json.dump(corpus_data, f, ensure_ascii=False, indent=2)

        size_mb = Path(corpus_file).stat().st_size / (1024*1024)
        print(f"✓ {corpus_file} ({size_mb:.2f} MB)")

        # 2. Índices
        indices_file = f'{base_name}_indices_completos.json'
        with open(indices_file, 'w', encoding='utf-8') as f:
            json.dump(self.indices, f, ensure_ascii=False, indent=2)

        size_kb = Path(indices_file).stat().st_size / 1024
        print(f"✓ {indices_file} ({size_kb:.2f} KB)")

        # 3. Reporte de calidad
        quality_report = self.generate_quality_report()
        quality_file = f'{base_name}_calidad_final.json'
        with open(quality_file, 'w', encoding='utf-8') as f:
            json.dump(quality_report, f, ensure_ascii=False, indent=2)

        size_kb = Path(quality_file).stat().st_size / 1024
        print(f"✓ {quality_file} ({size_kb:.2f} KB)")

        # 4. Log de procesamiento
        log_file = f'{base_name}_log_procesamiento.jsonl'
        with open(log_file, 'w', encoding='utf-8') as f:
            for metric in self.metrics:
                f.write(json.dumps(metric, ensure_ascii=False) + '\n')

        size_kb = Path(log_file).stat().st_size / 1024
        print(f"✓ {log_file} ({size_kb:.2f} KB)")

        print("\n✅ Exportación completada\n")

