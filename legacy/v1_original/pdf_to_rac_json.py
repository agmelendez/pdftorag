class FastPDFExtractor:
    """Extractor rápido y robusto."""

    def __init__(self):
        self.normalizer = TextNormalizer()

    def extract_pdf(self, pdf_path: str) -> Dict[str, Any]:
        """Extrae PDF completo."""
        pdf_id = Path(pdf_path).stem

        document = {
            'document_id': pdf_id,
            'filename': Path(pdf_path).name,
            'timestamp': datetime.now().isoformat(),
            'metadata': self._extract_metadata(pdf_path),
            'pages': []
        }

        try:
            with pdfplumber.open(pdf_path) as pdf:
                for page_num, page in enumerate(pdf.pages, 1):
                    page_data = self._extract_page(page, page_num)
                    document['pages'].append(page_data)

        except Exception as e:
            document['error'] = str(e)

        return document

    def _extract_metadata(self, pdf_path: str) -> Dict[str, Any]:
        """Extrae metadata del PDF."""
        metadata = {
            'filename': Path(pdf_path).name,
            'file_size_bytes': os.path.getsize(pdf_path),
            'fingerprint': self._fingerprint(pdf_path),
            'title': '',  # Initialize to empty strings
            'author': '',
            'page_count': 0  # Initialize to 0
        }

        try:
            reader = pypdf.PdfReader(pdf_path)
            if reader.metadata:
                # Explicitly convert to string to ensure JSON serializability
                # Use str() to resolve any potential pypdf.generic.IndirectObject
                # which might not be directly JSON serializable.
                metadata['title'] = str(reader.metadata.get('/Title', ''))
                metadata['author'] = str(reader.metadata.get('/Author', ''))
            metadata['page_count'] = len(reader.pages)
        except Exception:
            # If an error occurs, the initialized default values will be used.
            pass

        return metadata

    def _extract_page(self, page, page_num: int) -> Dict[str, Any]:
        """Extrae contenido de página."""
        # Texto
        raw_text = page.extract_text() or ""
        text_content = self.normalizer.normalize(raw_text)

        # Tablas
        tables = []
        try:
            table_list = page.extract_tables(table_settings={
                "vertical_strategy": "lines",
                "horizontal_strategy": "lines"
            })

            if table_list:
                for idx, table in enumerate(table_list):
                    if table and len(table) > 1:
                        try:
                            df = pd.DataFrame(table[1:], columns=table[0])
                            tables.append({
                                'table_id': idx,
                                'rows': len(df),
                                'columns': len(df.columns),
                                'headers': list(df.columns),
                                'data': df.to_dict('records')
                            })
                        except:
                            pass
        except:
            pass

        # Calcular calidad
        quality = self.normalizer.estimate_quality(text_content, len(tables))

        return {
            'page_number': page_num,
            'text': {
                'content': text_content,
                'word_count': len(text_content.split()) if text_content else 0,
                'has_content': bool(text_content.strip()),
                'quality_score': quality,
                'normalized': True
            },
            'tables': tables
        }

    def _fingerprint(self, pdf_path: str) -> str:
        """Calcula fingerprint del PDF."""
        try:
            with open(pdf_path, 'rb') as f:
                header = f.read(min(1024*100, os.path.getsize(pdf_path)))
            return hashlib.sha256(header).hexdigest()[:12]
        except:
            return 'unknown'

