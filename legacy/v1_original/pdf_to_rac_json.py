class TextNormalizer:
    """Normaliza texto sin perder contenido."""

    @staticmethod
    def normalize(text: str) -> str:
        """Normalización suave y segura."""
        if not text:
            return ""

        # Solo normalizar espacios problemáticos
        text = re.sub(r'\n{3,}', '\n\n', text)      # Máximo 2 saltos
        text = re.sub(r' {2,}', ' ', text)          # Espacios múltiples

        # Limpiar bordes
        lines = [line.strip() for line in text.split('\n')]
        lines = [line for line in lines if line.strip()]

        return '\n'.join(lines)

    @staticmethod
    def estimate_quality(text: str, tables_count: int = 0) -> float:
        """Estima calidad REAL (0.0-1.0)."""
        if not text or len(text) < 50:
            return 0.0

        words = len(text.split())

        # Palabras por página (aproximado)
        word_score = min(words / 300, 1.0)

        # Tabla bonus (si hay tablas, aumenta puntuación)
        table_bonus = min(tables_count * 0.05, 0.2)

        score = word_score * 0.8 + table_bonus
        return round(min(max(score, 0.0), 1.0), 3)

